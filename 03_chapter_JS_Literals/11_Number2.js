// Decimal numbers
let count = 10;
let negative = -5;
let decimal = 3.14;
console.log(typeof count); // "number"
console.log("Decimal: " + decimal); // "Decimal: 3.14"

// Binary numbers
let binary = 0b1010; // binary literal (10 in decimal)
console.log(typeof binary); // "number"
console.log("Binary: " + binary); // "Binary: 10"

// Octal numbers
let octal = 0o52; // octal literal (42 in decimal)
console.log(typeof octal); // "number"
console.log("Octal: " + octal); // "Octal: 42"

// Hexadecimal numbers
let hex = 0x2A; // hexadecimal literal (42 in decimal)
console.log(typeof hex); // "number"
console.log("Hexadecimal: " + hex); // "Hexadecimal: 42"

// Floating-point numbers
let num1 = 3.14; // floating-point literal
let num2 = 2.5e3; // exponential notation literal (2500 in decimal)
let num3 = -0.5; // negative floating-point literal
let num4 = .5; // shorthand for 0.5
console.log(typeof num1); // "number"
console.log("Float: " + num1); // "Float: 3.14"

// Exponential notation
let num5 = 1.23e4; // exponential notation literal (12300 in decimal)
let num6 = 5.67e-3; // small number literal (0.00567 in decimal)
let num7 = -2.5e2; // negative exponential notation literal (-250 in decimal)
let num8 = 2E10; // large number literal (20000000000 in decimal)








