let s = "Hi,  ";
console.log(typeof s); // Output: string

s += "How are you?"; // Concatenation using += operator
console.log(s); // Output: Hi, How are you?

console.log("Hello" + " " + "World"); // Output: Hello World
console.log("Hello",  "Madhu"); // Output: Hello Madhu
console.log("Hello",1,2,3,  "Madhu", true); // Output: Hello 1 2 3 Madhu true
