// Logical Operators
// Logical AND (&&)
let a = true;
let b = false;  
console.log(a && b); // Output: false (both values must be true for the result to be true)

// Logical OR (||)
console.log(a || b); // Output: true (at least one value must be true for the result to be true)

// Logical NOT (!)
console.log(!a);